/**
 * A-01: taken FIRST inside a §2.6 FAILED_CLEAN restore transaction. ACCESS
 * SHARE on source_records conflicts only with ACCESS EXCLUSIVE — M217's first
 * lock — so while the restore transaction lives no M217 can take its lock pair
 * (its own NOWAIT fails 55P03 and it applies nothing), and an M217 that already
 * holds it makes THIS NOWAIT fail instead (restore refused, freeze kept). The
 * in-transaction M217 re-read that follows is therefore still true at COMMIT.
 */
export const RESTORE_M217_EXCLUSION_LOCK_SQL = `LOCK TABLE public.central_needs_source_records IN ACCESS SHARE MODE NOWAIT`;

/**
 * §2.2 verification: EXECUTE per (function, role). $1 text[] roles. The
 * superuser / owner-equivalent flags mark grantees that are privileged paths
 * (§2.2: owner/superuser is not an ordinary client path), not client roles.
 */
export const FREEZE_PRIVILEGES_SQL = `SELECT f.fn, r.role,
       has_function_privilege(r.role, f.fn::regprocedure, 'EXECUTE') AS can_execute,
       COALESCE((SELECT rolsuper FROM pg_catalog.pg_roles WHERE rolname = r.role), false) AS superuser,
       pg_catalog.pg_has_role(r.role, (SELECT pg_catalog.pg_get_userbyid(proowner) FROM pg_catalog.pg_proc
                                        WHERE oid = f.fn::regprocedure), 'USAGE') AS owner_equivalent
  FROM unnest(${textArray(FREEZE_SIGNATURES)}) AS f(fn)
 CROSS JOIN unnest($1::text[]) AS r(role)
 ORDER BY f.fn, r.role`;

