/** Literal for constants only (never operator input). */
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;
const textArray = (xs) => `ARRAY[${xs.map(lit).join(', ')}]::text[]`;
const procArray = (xs) => `ARRAY[${xs.map(lit).join(', ')}]::regprocedure[]`;

/** UTC text with microseconds: comparable as a string, and castable back to timestamptz. */
export const utcText = (expr) => `to_char((${expr}) AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"')`;

/** Schema-qualified function identity, independent of search_path. */
const FN_IDENTITY = `(n.nspname || '.' || p.proname || '(' || pg_catalog.oidvectortypes(p.proargtypes) || ')')`;

/**
 * H8 ACL tuples as one jsonb array: function identity, owner, grantee,
 * grantor, privilege, grantable — from
 * aclexplode(COALESCE(proacl, acldefault('f', proowner))), so a NULL (default)
 * ACL is represented by the grants it actually confers.
 */
const aclTuplesJson = (procs) => `(SELECT COALESCE(jsonb_agg(jsonb_build_object(
      'fn', ${FN_IDENTITY},
      'owner', pg_catalog.pg_get_userbyid(p.proowner)::text,
      'grantee', CASE WHEN a.grantee = 0 THEN 'PUBLIC' ELSE pg_catalog.pg_get_userbyid(a.grantee)::text END,
      'grantor', CASE WHEN a.grantor = 0 THEN 'PUBLIC' ELSE pg_catalog.pg_get_userbyid(a.grantor)::text END,
      'privilege', a.privilege_type,
      'grantable', a.is_grantable)
      ORDER BY ${FN_IDENTITY}, a.grantee, a.grantor, a.privilege_type), '[]'::jsonb)
    FROM pg_catalog.pg_proc p
    JOIN pg_catalog.pg_namespace n ON n.oid = p.pronamespace
    CROSS JOIN LATERAL pg_catalog.aclexplode(COALESCE(p.proacl, pg_catalog.acldefault('f', p.proowner))) a
   WHERE p.oid = ANY (${procs}))`;

/** Raw proacl text per function, for evidence only (never compared). */
const aclTextJson = (procs) => `(SELECT jsonb_object_agg(${FN_IDENTITY}, COALESCE(p.proacl::text, '(default)'))
    FROM pg_catalog.pg_proc p JOIN pg_catalog.pg_namespace n ON n.oid = p.pronamespace
   WHERE p.oid = ANY (${procs}))`;

const A0_ROW = (r) => `jsonb_build_object(
      'id', ${r}.id, 'status', ${r}.status, 'plan_id', ${r}.plan_id, 'organization_id', ${r}.organization_id,
      'revision_number', ${r}.revision_number, 'approved_by', ${r}.approved_by,
      'approved_at', ${utcText(`${r}.approved_at`)}, 'updated_at', ${utcText(`${r}.updated_at`)})`;

const CENSUS_ROW = (a) => `jsonb_build_object('id', ${a}.id, 'action', ${a}.action, 'entity_id', ${a}.entity_id,
      'organization_id', ${a}.organization_id, 'created_at', ${utcText(`${a}.created_at`)})`;

/**
 * D-02 body fingerprints, one per signature (NULL if the function does not
 * exist): md5 over the function's oid, source, language, result type,
 * security, volatility, strictness, parallel safety, settings, owner and
 * argument types. Nothing in it depends on the session (no pg_get_functiondef
 * rendering, no search_path), so a T0 value and a later value compare exactly.
 */
const bodyFingerprintsJson = (sigs) => `(SELECT jsonb_object_agg(s.sig, (
      SELECT md5(jsonb_build_array(p.oid::text, p.prosrc, p.prolang::text, p.prorettype::text, p.proretset, p.prosecdef,
                                   p.provolatile::text, p.proisstrict, p.proparallel::text, p.proconfig, p.proowner::text,
                                   p.proargtypes::text)::text)
        FROM pg_catalog.pg_proc p WHERE p.oid = pg_catalog.to_regprocedure(s.sig)))
    FROM unnest(${textArray(sigs)}) AS s(sig))`;

