/**
 * D-02: is any backend executing M217 right now? One statement, three reads:
 *   locks    — any OTHER backend, or a prepared transaction (pid NULL),
 *              holding or awaiting a ShareLock-or-stronger lock on either §1
 *              relation of THIS database (ordinary client DML never takes
 *              one; M217 holds ACCESS EXCLUSIVE / EXCLUSIVE from its lock pair
 *              until COMMIT);
 *   sessions — any other backend with an open transaction whose current query
 *              carries an M217-only token (its prelude runs before the locks);
 *   hidden   — '<insufficient privilege>' sessions (what the runner cannot see
 *              it cannot prove absent).
 */
export const M217_IN_FLIGHT_SQL = `SELECT
  (SELECT COALESCE(jsonb_agg(jsonb_build_object('pid', l.pid, 'relation', c.relname::text, 'mode', l.mode, 'granted', l.granted,
          'virtualtransaction', l.virtualtransaction) ORDER BY l.pid, c.relname, l.mode), '[]'::jsonb)
     FROM pg_catalog.pg_locks l
     JOIN pg_catalog.pg_class c ON c.oid = l.relation
    WHERE l.locktype = 'relation'
      AND l.database = (SELECT d.oid FROM pg_catalog.pg_database d WHERE d.datname = pg_catalog.current_database())
      AND l.relation = ANY (ARRAY[${M217_LOCKED_RELATIONS.map((r) => `${lit(r)}::regclass`).join(', ')}]::oid[])
      AND l.pid IS DISTINCT FROM pg_catalog.pg_backend_pid()
      AND l.mode IN ('ShareLock', 'ShareRowExclusiveLock', 'ExclusiveLock', 'AccessExclusiveLock')) AS locks,
  (SELECT COALESCE(jsonb_agg(jsonb_build_object('pid', a.pid, 'state', a.state, 'backend_type', a.backend_type,
          'xact_start', ${utcText('a.xact_start')}) ORDER BY a.pid), '[]'::jsonb)
     FROM pg_catalog.pg_stat_activity a
    WHERE a.datname = pg_catalog.current_database()
      AND a.pid <> pg_catalog.pg_backend_pid()
      AND a.xact_start IS NOT NULL
      AND (${M217_IN_FLIGHT_TOKENS.map((t) => `position(${lit(t)} IN a.query) > 0`).join(' OR ')})) AS sessions,
  (SELECT COALESCE(jsonb_agg(a.pid ORDER BY a.pid), '[]'::jsonb)
     FROM pg_catalog.pg_stat_activity a
    WHERE a.datname = pg_catalog.current_database()
      AND a.pid <> pg_catalog.pg_backend_pid()
      AND a.query = '<insufficient privilege>') AS hidden,
  current_user::text AS runner`;

const fnAttributes = (sig) => `(SELECT jsonb_build_object(
      'volatile', p.provolatile, 'secdef', p.prosecdef, 'strict', p.proisstrict,
      'returns', pg_catalog.format_type(p.prorettype, NULL),
      'search_path_pinned', COALESCE('search_path=public, pg_temp' = ANY (p.proconfig), false),
      'authenticated', has_function_privilege('authenticated', p.oid, 'EXECUTE'),
      'service_role', has_function_privilege('service_role', p.oid, 'EXECUTE'),
      'anon', has_function_privilege('anon', p.oid, 'EXECUTE'),
      'public_entry', EXISTS (SELECT 1 FROM pg_catalog.aclexplode(COALESCE(p.proacl, pg_catalog.acldefault('f', p.proowner))) x
                               WHERE x.grantee = 0))
    FROM pg_catalog.pg_proc p WHERE p.oid = to_regprocedure(${lit(sig)}))`;

/** H10 catalog verification (read-only). */
export const POST_APPLY_CATALOG_SQL = `SELECT
  (SELECT COALESCE(jsonb_object_agg(x.proname, x.n), '{}'::jsonb) FROM (
     SELECT p.proname::text AS proname, count(*)::int AS n
       FROM pg_catalog.pg_proc p JOIN pg_catalog.pg_namespace ns ON ns.oid = p.pronamespace
      WHERE ns.nspname = 'public' AND p.proname = ANY (${textArray(EXACT_OVERLOAD_NAMES)})
      GROUP BY p.proname) x) AS overloads,
  ${fnAttributes(M217_OBJECTS.classifier)} AS classifier,
  ${fnAttributes(M217_OBJECTS.lineageHelper)} AS lineage_helper,
  ${fnAttributes(M217_OBJECTS.fenceFunction)} AS fence_function,
  (SELECT jsonb_build_object('type', t.tgtype::int, 'column_list', t.tgattr::text, 'enabled', t.tgenabled::text,
          'function', (SELECT ${FN_IDENTITY} FROM pg_catalog.pg_proc p JOIN pg_catalog.pg_namespace n ON n.oid = p.pronamespace
                        WHERE p.oid = t.tgfoid),
          'definition', pg_catalog.pg_get_triggerdef(t.oid))
     FROM pg_catalog.pg_trigger t
    WHERE t.tgrelid = 'public.central_needs_plan_revisions'::regclass AND t.tgname = ${lit(M217_OBJECTS.fenceTrigger)}) AS fence_trigger,
  (SELECT jsonb_build_object('type', c.contype::text, 'validated', c.convalidated, 'definition', pg_catalog.pg_get_constraintdef(c.oid))
     FROM pg_catalog.pg_constraint c
    WHERE c.conrelid = 'public.central_needs_source_records'::regclass AND c.conname = ${lit(M217_OBJECTS.valueContract)}) AS value_contract,
  jsonb_build_object(${C5_BLOCKER_CODES.map((c) => `${lit(c)},
    position(${lit(`'${c}'`)} IN pg_catalog.pg_get_functiondef('public._phoenix_central_needs_review_blockers_v1(uuid)'::regprocedure)) > 0`).join(',\n    ')}) AS blocker_vocabulary`;

/**
 * H10 "no unexpected lifecycle writer": functions whose body UPDATEs
 * plan_revisions.status, and functions that INSERT plan revisions.
 */
export const LIFECYCLE_WRITERS_SQL = `SELECT fn, updates_status, inserts_revision FROM (
  SELECT ${FN_IDENTITY} AS fn,
         p.prosrc ~* 'update\\s+(public\\s*\\.\\s*)?central_needs_plan_revisions\\M[^;]*\\mset\\M[^;]*\\mstatus\\s*=' AS updates_status,
         p.prosrc ~* 'insert\\s+into\\s+(public\\s*\\.\\s*)?central_needs_plan_revisions\\M' AS inserts_revision
    FROM pg_catalog.pg_proc p JOIN pg_catalog.pg_namespace n ON n.oid = p.pronamespace
   WHERE n.nspname NOT IN ('pg_catalog', 'information_schema')
     AND p.prosrc ILIKE '%central_needs_plan_revisions%') w
 WHERE updates_status OR inserts_revision
 ORDER BY fn`;

