/**
 * T0, S0, A0 (widened per H4), the complete submit/approve ACL (H8), the
 * reject ACL (H7 reference), the H11 lifecycle-audit census L0, the D-02 body
 * fingerprints of every function M217 replaces (plus submit and reject) and
 * the runner identity — all from ONE statement, i.e. one READ COMMITTED
 * statement snapshot. Splitting it would let a commit land between the parts.
 */
export const T0_SNAPSHOT_SQL = `WITH clk AS MATERIALIZED (SELECT pg_catalog.clock_timestamp() AS t0)
SELECT
  ${utcText('clk.t0')} AS t0,
  current_user::text AS runner_current_user,
  session_user::text AS runner_session_user,
  pg_catalog.pg_backend_pid() AS runner_pid,
  pg_catalog.current_database()::text AS database,
  pg_catalog.txid_current_snapshot()::text AS txid_snapshot,
  (SELECT COALESCE(jsonb_agg(r.id ORDER BY r.id), '[]'::jsonb)
     FROM public.central_needs_plan_revisions r WHERE r.status = 'submitted') AS s0,
  (SELECT COALESCE(jsonb_agg(${A0_ROW('r')} ORDER BY r.id), '[]'::jsonb)
     FROM public.central_needs_plan_revisions r WHERE r.status IN ('approved', 'superseded')) AS a0,
  ${aclTuplesJson(procArray(FREEZE_SIGNATURES))} AS acl0,
  ${aclTextJson(procArray(FREEZE_SIGNATURES))} AS acl0_text,
  ${aclTuplesJson(procArray([REJECT_SIGNATURE]))} AS reject_acl0,
  (SELECT COALESCE(jsonb_agg(${CENSUS_ROW('a')} ORDER BY a.id), '[]'::jsonb)
     FROM public.audit_logs a WHERE a.action = ANY (${textArray(LIFECYCLE_AUDIT_ACTIONS)})) AS l0,
  ${bodyFingerprintsJson(FINGERPRINT_SIGNATURES)} AS fingerprints
FROM clk`;

