// ===========================================================================
// C5 ACTIVATION — SQL text (C5 v1.9 §2 / §21, Owner hardening H1-H13).
//
// Text only. Nothing here connects to a database; c5-activation-runbook.mjs
// executes these statements and c5-activation-contract.mjs judges what they
// return. One module for the text means the loopback rehearsal, the CLI and
// the tests all run exactly the same reads.
//
// WHAT MUTATES: every statement in this module is a SELECT that reads, with
// exactly ONE exception — REJECT_RPC_SQL, which CALLS the canonical reject
// RPC (a governed, audited mutation executed AS the designated operator
// identity, §2.4 / H6). DCL_LOCK_TIMEOUT_SQL only sets a transaction-local
// timeout and RESTORE_M217_EXCLUSION_LOCK_SQL only takes a transaction-scoped
// ACCESS SHARE lock (A-01); neither writes. The other mutating text in the
// activation (the §2.2 freeze and the
// §2.6 restore DCL) is generated by planFreezeStatements() /
// planRestoreStatements() in the contract from a sealed ACL snapshot, never
// from operator input, and lives in no constant here.
//
// Timestamps that decisions compare are rendered as UTC text with microsecond
// precision (utcText), so two reads in sessions with different TimeZone
// settings still compare equal.
// ===========================================================================
