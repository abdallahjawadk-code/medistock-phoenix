describe('buildPremiumPrintHtml: RTL/LTR, branding, metadata, date-safety, same rows as XLSX', () => {
  it('sets dir="rtl" for Arabic and dir="ltr" for English', () => {
    const ar = buildPremiumPrintHtml(baseConfig({ lang: 'ar' }));
    const en = buildPremiumPrintHtml(baseConfig({ lang: 'en' }));
    expect(ar).toContain('<html dir="rtl" lang="ar">');
    expect(en).toContain('<html dir="ltr" lang="en">');
  });

  it('includes report title, module name, brand, footer, and metadata lines', () => {
    const html = buildPremiumPrintHtml(baseConfig());
    expect(html).toContain('Inventory Report');
    expect(html).toContain('Status Editor');
    expect(html).toContain('Generated by MediStock Phoenix');
    expect(html).toContain('Generated at');
    expect(html).toContain('Filters');
    expect(html).toContain('Rows');
  });

  it('renders date columns as readable text, never "###" or "Invalid Date"', () => {
    const columns: ProfessionalReportColumn<Row>[] = [
      { key: 'when', label: 'When', value: r => String(r.when ?? '—'), dateColumn: 'date', excelValue: r => r.when ?? null, ltr: true },
    ];
    const rows: Row[] = [
      { id: '1', name: 'A', qty: 1, when: '2026-07-01T00:00:00.000Z', status: 'available' },
      { id: '2', name: 'B', qty: 1, when: null, status: 'available' },
      { id: '3', name: 'C', qty: 1, when: 'not-a-real-date', status: 'available' },
    ];
    const html = buildPremiumPrintHtml(baseConfig({ columns, rows }));
    expect(html).not.toContain('###');
    expect(html).not.toMatch(/Invalid Date/i);
    expect(html).toContain('2026-07-01');
  });

  it('styles a bold/colored table header and alternating row background', async () => {
    const html = buildPremiumPrintHtml(baseConfig());
    expect(html).toContain('th { background:');
    expect(html).toContain('font-weight: 700');
    expect(html).toContain('tbody tr:nth-child(even)');
  });

  it('escapes HTML-injection attempts in row values', () => {
    const html = buildPremiumPrintHtml(baseConfig({ rows: [{ id: '1', name: '<script>alert(1)</script>', qty: 1, when: null, status: 'available' }] }));
    expect(html).not.toContain('<script>alert');
    expect(html).toContain('&lt;script&gt;');
  });

  it('renders the translated empty-state message instead of an empty table when there are zero rows', () => {
    const html = buildPremiumPrintHtml(baseConfig({ rows: [], emptyMessage: 'No records' }));
    expect(html).toContain('No records');
    expect(html).not.toContain('<table>');
  });

  it('same config (same rows/columns) feeds both buildProfessionalWorkbook and buildPremiumPrintHtml — no divergent row set between XLSX and PDF', async () => {
    const config = baseConfig({ rows: [
      { id: '1', name: 'Alpha', qty: 1, when: null, status: 'available' },
      { id: '2', name: 'Beta', qty: 2, when: null, status: 'missing' },
    ] });
    const html = buildPremiumPrintHtml(config);
    const wb = await buildProfessionalWorkbook(config);
    const ws = wb.worksheets[0];
    const xlsxNames: string[] = [];
    ws.eachRow(row => {
      const v = row.getCell(1).value;
      if (v === 'Alpha' || v === 'Beta') xlsxNames.push(v);
    });
    expect(html).toContain('Alpha');
    expect(html).toContain('Beta');
    expect(xlsxNames).toEqual(['Alpha', 'Beta']);
  });
});

