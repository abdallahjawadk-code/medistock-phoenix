const SRC = join(__dirname, '../../../');
const ROOT = join(__dirname, '../../../../');
const read = (rel: string) => readFileSync(join(SRC, rel), 'utf8');
const moduleSrc = read('shared/lib/professional-export.ts');

interface Row { id: string; uuid?: string; name: string; qty: number; when: string | Date | null; status: 'missing' | 'available'; }

function baseConfig(overrides: Partial<ProfessionalExportConfig<Row>> = {}): ProfessionalExportConfig<Row> {
  const columns: ProfessionalReportColumn<Row>[] = [
    { key: 'name', label: 'Name', value: r => r.name },
    { key: 'qty', label: 'Qty', value: r => String(r.qty), numeric: true, excelValue: r => r.qty },
    { key: 'when', label: 'When', value: r => String(r.when ?? '—'), ltr: true },
  ];
  return {
    reportTitle: 'Inventory Report',
    moduleName: 'Status Editor',
    generatedAt: new Date('2026-07-04T10:30:00'),
    filtersSummary: 'All',
    columns,
    rows: [{ id: 'row-1', name: 'Paracetamol', qty: 5, when: '2026-07-01', status: 'available' }],
    lang: 'en',
    fileNameBase: 'medistock-report',
    footerText: 'Generated by MediStock Phoenix',
    labels: { generatedAt: 'Generated at', filtersSummary: 'Filters', rowCount: 'Rows' },
    ...overrides,
  };
}

