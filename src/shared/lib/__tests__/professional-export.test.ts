describe('buildMultiSheetProfessionalWorkbook: parent + drill-down detail in one workbook', () => {
  interface DetailRow { id: string; parent: string; qty: number; }

  function detailConfig(overrides: Partial<ProfessionalExportConfig<DetailRow>> = {}): ProfessionalExportConfig<DetailRow> {
    const columns: ProfessionalReportColumn<DetailRow>[] = [
      { key: 'parent', label: 'Parent', value: r => r.parent, ltr: true },
      { key: 'qty', label: 'Qty', value: r => String(r.qty), numeric: true, excelValue: r => r.qty },
    ];
    return {
      reportTitle: 'Detail Report',
      moduleName: 'Detail',
      generatedAt: new Date('2026-07-04T10:30:00'),
      filtersSummary: 'All',
      columns,
      rows: [{ id: 'd-1', parent: 'ORD-1', qty: 3 }],
      lang: 'en',
      fileNameBase: 'medistock-detail',
      footerText: 'Generated by MediStock Phoenix',
      labels: { generatedAt: 'Generated at', filtersSummary: 'Filters', rowCount: 'Rows' },
      ...overrides,
    };
  }

  it('produces one workbook with one worksheet per config, in order', async () => {
    const wb = await buildMultiSheetProfessionalWorkbook([baseConfig({ moduleName: 'Orders' }), detailConfig({ moduleName: 'Lines' })]);
    expect(wb.worksheets.length).toBe(2);
    expect(wb.worksheets[0].name).toBe('Orders');
    expect(wb.worksheets[1].name).toBe('Lines');
  });

  it('each sheet carries its OWN rows — the parent sheet never leaks detail rows and vice versa', async () => {
    const wb = await buildMultiSheetProfessionalWorkbook([
      baseConfig({ moduleName: 'Orders', rows: [{ id: '1', name: 'ORD-1', qty: 1, when: null, status: 'available' }] }),
      detailConfig({ moduleName: 'Lines', rows: [{ id: 'd-1', parent: 'ORD-1', qty: 3 }, { id: 'd-2', parent: 'ORD-1', qty: 7 }] }),
    ]);
    const ordersValues: unknown[] = [];
    wb.worksheets[0].eachRow(row => ordersValues.push(row.getCell(1).value));
    const linesValues: unknown[] = [];
    wb.worksheets[1].eachRow(row => linesValues.push(row.getCell(1).value));
    expect(ordersValues.filter(v => v === 'ORD-1').length).toBe(1);
    expect(linesValues.filter(v => v === 'ORD-1').length).toBe(2);
  });

  it('a single-sheet buildProfessionalWorkbook and a one-config buildMultiSheetProfessionalWorkbook produce the same sheet name and row count', async () => {
    const cfg = baseConfig();
    const single = await buildProfessionalWorkbook(cfg);
    const multi = await buildMultiSheetProfessionalWorkbook([cfg]);
    expect(multi.worksheets.length).toBe(1);
    expect(multi.worksheets[0].name).toBe(single.worksheets[0].name);
    expect(multi.worksheets[0].rowCount).toBe(single.worksheets[0].rowCount);
  });

  it('exportProfessionalMultiSheetXlsx never throws in a DOM-less test env — resolves to false instead of crashing', async () => {
    await expect(exportProfessionalMultiSheetXlsx([baseConfig(), detailConfig()], 'medistock-full')).resolves.toBe(false);
  });

  it('exportProfessionalMultiSheetXlsx downloads with a .xlsx extension and the correct OOXML MIME type (same contract as the single-sheet export)', () => {
    expect(moduleSrc).toContain('export async function exportProfessionalMultiSheetXlsx');
    const fn = moduleSrc.slice(moduleSrc.indexOf('export async function exportProfessionalMultiSheetXlsx'));
    expect(fn).toContain("buildStableFileName(fileNameBase, 'xlsx')");
    expect(fn).toContain("'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'");
  });
});

