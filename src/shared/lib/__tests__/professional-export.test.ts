/**
 * EXPORT-PROFESSIONAL-XLSX-PDF-A / EXPORT-PROFESSIONAL-XLSX-PDF-B / EXPORT-XLSX-DYNAMIC-IMPORT-A
 *
 * Tests for the shared professional export config layer
 * (src/shared/lib/professional-export.ts).
 *
 * EXPORT-PROFESSIONAL-XLSX-PDF-B: the user explicitly required real Excel
 * export, not CSV. `exceljs` is now an approved, installed dependency (see
 * package.json) and `exportProfessionalXlsx`/`buildProfessionalWorkbook` are
 * the PRIMARY "Excel export" path, producing a true `.xlsx` workbook
 * (Creator/Created/Modified metadata, RTL worksheet view, frozen header,
 * auto-filter, styled header/alternating rows, real Date cells with explicit
 * numFmt so dates can never render as `###`). `exportProfessionalCsv` is
 * kept only as an explicitly-marked legacy/optional fallback, not wired to
 * any screen. PDF/print still uses the existing dependency-free browser
 * print-to-PDF path (no PDF library was added — jsPDF/pdfmake/pdf-lib are
 * out of scope for this phase).
 *
 * EXPORT-XLSX-DYNAMIC-IMPORT-A: ExcelJS is no longer a top-level static
 * import in professional-export.ts (that would bundle its ~900KB into the
 * app's main chunk, loaded on every visit even though export is rarely
 * used). It's now loaded via a lazy `import('exceljs')` inside
 * `buildProfessionalWorkbook`, which is therefore now async — every test
 * below that calls it awaits the result. This test file itself imports
 * ExcelJS statically because it's test-only code (never shipped in the app
 * bundle), so it can use `ExcelJS.Workbook`/`ExcelJS.Row`/etc. as before.
 *
 * Run: npm test -- --run
 */
